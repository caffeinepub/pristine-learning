// ─── Tool Components ──────────────────────────────────────────────────────────

function StudyMaterialTool() {
  const [subject, setSubject] = useState('');
  const [curriculum, setCurriculum] = useState('');
  const [result, setResult] = useState('');
  const [loading, setLoading] = useState(false);

  const handleGenerate = () => {
    if (!subject || !curriculum) return;
    setLoading(true);
    setTimeout(() => {
      setResult(generateStudyMaterial(subject, curriculum));
      setLoading(false);
    }, 800);
  };

  return (
    <div className="space-y-4">
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
        <div className="space-y-1">
          <Label>Subject</Label>
          <Input placeholder="e.g. Mathematics, Physics…" value={subject} onChange={e => setSubject(e.target.value)} />
        </div>
        <div className="space-y-1">
          <Label>Curriculum</Label>
          <Select value={curriculum} onValueChange={setCurriculum}>
            <SelectTrigger><SelectValue placeholder="Select curriculum" /></SelectTrigger>
            <SelectContent>
              {CURRICULA.map(c => <SelectItem key={c} value={c}>{c}</SelectItem>)}
            </SelectContent>
          </Select>
        </div>
      </div>
      <Button onClick={handleGenerate} disabled={!subject || !curriculum || loading} className="btn-primary gap-2">
        <Sparkles className="w-4 h-4" />
        {loading ? 'Generating…' : 'Generate Study Material'}
      </Button>
      {result && (
        <div className="bg-muted/30 rounded-xl p-5 border border-border">
          <pre className="whitespace-pre-wrap text-sm font-sans leading-relaxed">{result}</pre>
        </div>
      )}
    </div>
  );
}

function QuizTool() {
  const [topic, setTopic] = useState('');
  const [curriculum, setCurriculum] = useState('');
  const [questions, setQuestions] = useState<Array<{ question: string; options: string[]; answer: number }>>([]);
  const [selected, setSelected] = useState<Record<number, number>>({});
  const [submitted, setSubmitted] = useState(false);
  const [loading, setLoading] = useState(false);

  const handleGenerate = () => {
    if (!topic || !curriculum) return;
    setLoading(true);
    setSelected({});
    setSubmitted(false);
    setTimeout(() => {
      setQuestions(generateQuiz(topic, curriculum));
      setLoading(false);
    }, 600);
  };

  const score = submitted
    ? questions.filter((q, i) => selected[i] === q.answer).length
    : 0;

  return (
    <div className="space-y-4">
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
        <div className="space-y-1">
          <Label>Topic</Label>
          <Input placeholder="e.g. Algebra, Photosynthesis…" value={topic} onChange={e => setTopic(e.target.value)} />
        </div>
        <div className="space-y-1">
          <Label>Curriculum</Label>
          <Select value={curriculum} onValueChange={setCurriculum}>
            <SelectTrigger><SelectValue placeholder="Select curriculum" /></SelectTrigger>
            <SelectContent>
              {CURRICULA.map(c => <SelectItem key={c} value={c}>{c}</SelectItem>)}
            </SelectContent>
          </Select>
        </div>
      </div>
      <Button onClick={handleGenerate} disabled={!topic || !curriculum || loading} className="btn-primary gap-2">
        <HelpCircle className="w-4 h-4" />
        {loading ? 'Generating…' : 'Generate Quiz'}
      </Button>

      {questions.length > 0 && (
        <div className="space-y-4">
          {submitted && (
            <div className={`p-4 rounded-xl border ${score >= 4 ? 'bg-green-50 border-green-200' : 'bg-amber-50 border-amber-200'}`}>
              <p className="font-semibold">Score: {score}/{questions.length}</p>
              <p className="text-sm text-muted-foreground">
                {score >= 4 ? '🎉 Excellent work!' : score >= 3 ? '👍 Good effort!' : '📚 Keep studying!'}
              </p>
            </div>
          )}
          {questions.map((q, qi) => (
            <div key={qi} className="bg-white rounded-xl border border-border p-4">
              <p className="font-medium text-sm mb-3">{qi + 1}. {q.question}</p>
              <div className="space-y-2">
                {q.options.map((opt, oi) => (
                  <button
                    key={oi}
                    onClick={() => !submitted && setSelected(prev => ({ ...prev, [qi]: oi }))}
                    className={`w-full text-left px-3 py-2 rounded-lg border text-sm transition-all ${
                      submitted
                        ? oi === q.answer
                          ? 'bg-green-50 border-green-400 text-green-700'
                          : selected[qi] === oi
                          ? 'bg-red-50 border-red-300 text-red-600'
                          : 'border-border'
                        : selected[qi] === oi
                        ? 'border-primary bg-primary/5 text-primary'
                        : 'border-border hover:border-primary/40'
                    }`}
                  >
                    {String.fromCharCode(65 + oi)}. {opt}
                  </button>
                ))}
              </div>
            </div>
          ))}
          {!submitted && (
            <Button
              onClick={() => setSubmitted(true)}
              disabled={Object.keys(selected).length < questions.length}
              className="btn-primary"
            >
              Submit Answers
            </Button>
          )}
          {submitted && (
            <Button variant="outline" onClick={() => { setSubmitted(false); setSelected({}); setQuestions([]); }}>
              Try Another Quiz
            </Button>
          )}
        </div>
      )}
    </div>
  );
}

function NoteSummarizerTool() {
  const [notes, setNotes] = useState('');
  const [summary, setSummary] = useState('');
  const [loading, setLoading] = useState(false);

  const handleSummarize = () => {
    if (!notes.trim()) return;
    setLoading(true);
    setTimeout(() => {
      setSummary(summarizeNotes(notes));
      setLoading(false);
    }, 600);
  };

  return (
    <div className="space-y-4">
      <div className="space-y-1">
        <Label>Paste Your Notes</Label>
        <Textarea
          placeholder="Paste your notes here to get a concise summary…"
          value={notes}
          onChange={e => setNotes(e.target.value)}
          rows={8}
          className="font-mono text-sm"
        />
        <p className="text-xs text-muted-foreground">{notes.split(' ').filter(Boolean).length} words</p>
      </div>
      <Button onClick={handleSummarize} disabled={!notes.trim() || loading} className="btn-primary gap-2">
        <FileText className="w-4 h-4" />
        {loading ? 'Summarizing…' : 'Summarize Notes'}
      </Button>
      {summary && (
        <div className="bg-muted/30 rounded-xl p-5 border border-border">
          <pre className="whitespace-pre-wrap text-sm font-sans leading-relaxed">{summary}</pre>
        </div>
      )}
    </div>
  );
}

